$ErrorActionPreference = "Stop"

$repoRoot = Resolve-Path (Join-Path $PSScriptRoot "..")
$bridgeRoot = Join-Path $repoRoot "discord_nas_bridge"
$bundleRoot = Join-Path $bridgeRoot "app"
$resolvedBridgeRoot = Resolve-Path $bridgeRoot

if (Test-Path $bundleRoot) {
  $resolvedBundleRoot = Resolve-Path $bundleRoot
  if (-not $resolvedBundleRoot.Path.StartsWith($resolvedBridgeRoot.Path, [System.StringComparison]::OrdinalIgnoreCase)) {
    throw "Refusing to remove bundle path outside discord_nas_bridge: $($resolvedBundleRoot.Path)"
  }
  Remove-Item -LiteralPath $resolvedBundleRoot.Path -Recurse -Force
}

New-Item -ItemType Directory -Path $bundleRoot | Out-Null

Copy-Item -LiteralPath (Join-Path $repoRoot "package.json") -Destination $bundleRoot
Copy-Item -LiteralPath (Join-Path $repoRoot "package-lock.json") -Destination $bundleRoot
Copy-Item -LiteralPath (Join-Path $repoRoot "tsconfig.json") -Destination $bundleRoot
Copy-Item -LiteralPath (Join-Path $repoRoot "src") -Destination (Join-Path $bundleRoot "src") -Recurse

$stamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss zzz"
@"
Generated by scripts/prepare-nas-bundle.ps1
Generated at: $stamp

This app/ directory is a deploy bundle for Synology/NAS Docker builds.
Do not edit it manually. Regenerate it from the repository root before upload.
"@ | Set-Content -Path (Join-Path $bundleRoot ".bundle-generated.txt") -Encoding UTF8

Write-Host "NAS bundle prepared: $bundleRoot"
